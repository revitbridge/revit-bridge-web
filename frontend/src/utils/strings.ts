export function uiText(english: string, ...values: unknown[]): string {
  const label = browserLanguage() === 'zh' && Object.hasOwn(zh, english) ? zh[english] : english
  return values.length ? label.replace(/\{(\d+)\}/g, (_, i: string) => String(values[Number(i)])) : label
}
